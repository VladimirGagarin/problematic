import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { samplePosts } from '../src/data/samplePosts.js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outFile = join(root, 'supabase', 'seed-posts.sql')

const esc = (value) => String(value ?? '').replaceAll("'", "''")

const pgArray = (values) => {
  const items = (values || []).map(esc).join("','")
  return items ? `ARRAY['${items}']` : 'ARRAY[]::text[]'
}

const rows = samplePosts.map((p) => {
  const fields = [
    esc(p.id),
    esc(p.title),
    esc(p.type),
    esc(p.category),
    pgArray(p.secondaryCategories),
    esc(p.difficulty),
    esc(p.problem),
    esc(p.author),
    esc(p.createdAt),
    pgArray(p.hints),
    esc(p.solution),
    esc(p.answer),
    esc(p.formula),
    esc(p.solutionStatus),
    0,
    0,
    0
  ]
  return `(${fields.join(', ')})`
})

const sql = `-- Generated by scripts/seed-posts.mjs. DO NOT EDIT by hand.
-- Run \`npm run seed:gen\` to regenerate. Engagements are zeroed on purpose:
-- \`${samplePosts.length}\` posts, each starting with 0 votes / 0 comments / 0 shares.

insert into public.posts (
  id, title, type, category, secondary_categories, difficulty, problem, author,
  created_at, hints, solution, answer, formula, solution_status,
  vote_count, comment_count, share_count
)
values
${rows.join(',\n')}
on conflict (id) do nothing;

update public.posts set vote_count = 0, comment_count = 0, share_count = 0;

select count(*) as posts_seeded, sum(vote_count) as total_votes, sum(comment_count) as total_comments, sum(share_count) as total_shares from public.posts;
`

mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(outFile, sql, 'utf8')

console.log(`Wrote ${samplePosts.length} posts (all engagements = 0) to ${outFile}`)